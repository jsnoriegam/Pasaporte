"""Split DNS: dominios que deben resolverse con el DNS de la VPN.

openconnect deja que ``vpnc-script`` configure las rutas y el DNS. Para
añadir dominios de split DNS sin tocar el script del sistema, generamos un
envoltorio que:

1. Añade los dominios a ``CISCO_SPLIT_DNS``, que ``vpnc-script`` usa para
   configurar systemd-resolved.
2. Llama al ``vpnc-script`` original con la misma fase (``$1``).
3. Si el script original no aplicó los dominios, los aplica directamente
   con ``resolvectl`` como dominios de enrutamiento (``~dominio``).

El envoltorio se ejecuta como root porque openconnect se lanza con
``pkexec`` o ``sudo``; solo contiene los dominios validados que escribe el
usuario.
"""

from __future__ import annotations

import os
import re
import shlex
import shutil
import stat
import tempfile
from pathlib import Path
from typing import Iterable

from PySide6.QtCore import QCoreApplication

# Etiqueta DNS: 1-63 caracteres, sin guion al principio ni al final.
_LABEL = r"[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?"
_DOMAIN_RE = re.compile(rf"^{_LABEL}(?:\.{_LABEL})*$")

VPNC_SCRIPT_CANDIDATES = (
    Path("/etc/vpnc/vpnc-script"),
    Path("/usr/libexec/vpnc-script"),
    Path("/usr/share/vpnc-scripts/vpnc-script"),
)


def normalize_domains(value: str | Iterable[str] | None) -> list[str]:
    """Normaliza una lista o una cadena separada por comas/espacios."""
    if value is None:
        return []

    if isinstance(value, str):
        parts = value.replace(",", " ").split()
    else:
        parts = []
        for item in value:
            parts.extend(str(item).replace(",", " ").split())

    domains: list[str] = []
    for part in parts:
        domain = part.strip().lower().lstrip("~").rstrip(".")
        if domain and domain not in domains:
            domains.append(domain)
    return domains


def domain_error(domain: str) -> str | None:
    if not domain:
        return QCoreApplication.translate(
            "SplitDNS", "Domain is empty."
        )
    if len(domain) > 253:
        return QCoreApplication.translate(
            "SplitDNS", "Domain is too long: {domain}"
        ).format(domain=domain)
    if not _DOMAIN_RE.match(domain):
        return QCoreApplication.translate(
            "SplitDNS", "Invalid domain: {domain}"
        ).format(domain=domain)
    return None


def validate_domains(domains: list[str]) -> list[str]:
    errors: list[str] = []
    for domain in domains:
        error = domain_error(domain)
        if error:
            errors.append(error)
    return errors


def has_custom_script(args: list[str]) -> bool:
    """True si ``extra_args`` ya contiene un --script."""
    for arg in args:
        if arg in {"-s", "--script"}:
            return True
        if arg.startswith("--script=") or arg.startswith("-s="):
            return True
        if arg.startswith("-s/") or arg.startswith("-s."):
            return True
    return False


def vpnc_script_path() -> Path | None:
    for candidate in VPNC_SCRIPT_CANDIDATES:
        if candidate.is_file():
            return candidate
    found = shutil.which("vpnc-script")
    return Path(found) if found else None


def resolvectl_path() -> Path | None:
    found = shutil.which("resolvectl")
    return Path(found) if found else None


def _runtime_dir() -> Path:
    base = os.environ.get("XDG_RUNTIME_DIR")
    if base:
        path = Path(base) / "pasaporte"
    else:
        path = Path.home() / ".cache" / "pasaporte"

    try:
        path.mkdir(parents=True, exist_ok=True)
        info = path.stat()
    except OSError as exc:
        raise ValueError(
            QCoreApplication.translate(
                "SplitDNS",
                "Could not create the split DNS directory: {error}",
            ).format(error=exc)
        ) from exc

    if not stat.S_ISDIR(info.st_mode) or info.st_uid != os.getuid():
        raise ValueError(
            QCoreApplication.translate(
                "SplitDNS",
                "The split DNS directory is not owned by the current user: "
                "{path}",
            ).format(path=path)
        )

    # El directorio debe ser privado: el envoltorio se ejecuta como root.
    if stat.S_IMODE(info.st_mode) & 0o077:
        try:
            path.chmod(0o700)
        except OSError:
            pass
    return path


def _wrapper_content(
    domains: list[str],
    base_script: Path,
    resolvectl: Path,
) -> str:
    joined = ",".join(domains)
    first = domains[0]
    domain_args = " ".join(shlex.quote("~" + domain) for domain in domains)
    base = shlex.quote(str(base_script))
    resolver = shlex.quote(str(resolvectl))

    return (
        "#!/bin/sh\n"
        "# Generated by Pasaporte for split DNS. Do not edit.\n"
        f"PASAPORTE_SPLIT_DNS={shlex.quote(joined)}\n"
        f"PASAPORTE_FIRST_DOMAIN={shlex.quote(first)}\n"
        'if [ -n "$CISCO_SPLIT_DNS" ]; then\n'
        '    CISCO_SPLIT_DNS="$CISCO_SPLIT_DNS,$PASAPORTE_SPLIT_DNS"\n'
        "else\n"
        '    CISCO_SPLIT_DNS="$PASAPORTE_SPLIT_DNS"\n'
        "fi\n"
        "export CISCO_SPLIT_DNS\n"
        "\n"
        f'{base} "$@"\n'
        "rc=$?\n"
        "\n"
        'case "$reason" in\n'
        "    connect|reconnect)\n"
        '        if [ -n "$TUNDEV" ]; then\n'
        f'            current=$({resolver} domain "$TUNDEV" 2>/dev/null '
        "| sed -n 's/^[^:]*: *//p')\n"
        '            case "$current" in\n'
        '                *"$PASAPORTE_FIRST_DOMAIN"*) ;;\n'
        f'                *) {resolver} domain "$TUNDEV" $current {domain_args} '
        ">/dev/null 2>&1 || true ;;\n"
        "            esac\n"
        f'            {resolver} flush-caches >/dev/null 2>&1 || true\n'
        "        fi\n"
        "        ;;\n"
        "esac\n"
        "\n"
        "exit $rc\n"
    )


def write_wrapper(domains: list[str]) -> Path:
    """Escribe un vpnc-script temporal con los dominios de split DNS."""
    domains = normalize_domains(domains)
    errors = validate_domains(domains)
    if errors:
        raise ValueError("\n".join(errors))
    if not domains:
        raise ValueError(
            QCoreApplication.translate(
                "SplitDNS", "At least one DNS domain is required."
            )
        )

    base_script = vpnc_script_path()
    if base_script is None:
        raise ValueError(
            QCoreApplication.translate(
                "SplitDNS",
                "vpnc-script was not found; split DNS needs it.",
            )
        )

    resolvectl = resolvectl_path()
    if resolvectl is None:
        raise ValueError(
            QCoreApplication.translate(
                "SplitDNS",
                "resolvectl was not found; split DNS needs "
                "systemd-resolved.",
            )
        )

    directory = _runtime_dir()
    fd, name = tempfile.mkstemp(
        dir=directory, prefix="vpnc-script-", suffix=".sh"
    )
    path = Path(name)
    try:
        os.fchmod(fd, 0o700)
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(
                _wrapper_content(domains, base_script, resolvectl)
            )
            handle.flush()
            os.fsync(handle.fileno())
    except Exception:
        try:
            os.close(fd)
        except OSError:
            pass
        path.unlink(missing_ok=True)
        raise
    return path
